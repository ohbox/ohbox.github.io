  var REVERSE = Object.create(null);
  Object.keys(ZH).forEach(function (en) {
    if (typeof ZH[en] === 'string' && ZH[en] && REVERSE[ZH[en]] == null) REVERSE[ZH[en]] = en;
  });
  var lang = window.PfxI18n ? window.PfxI18n.getLang() : 'en';
  var textMemory = new WeakMap();
  var attrMemory = new WeakMap();
  var ATTRS = ['aria-label', 'aria-roledescription', 'placeholder', 'title', 'alt', 'data-spec', 'data-focal'];

  function sourceOf(value) {
    return Object.prototype.hasOwnProperty.call(ZH, value) ? value : (REVERSE[value] || value);
  }

  function translated(source, targetLang) {
    if (targetLang !== 'zh') return source;
    var value = ZH[source];
    if (typeof value === 'string') return value;

    var m = source.match(/^Comment from (.+)$/);
    if (m) return '來自 ' + m[1] + ' 的留言';
    m = source.match(/^Thinking: (.+)$/);
    if (m) return '思考方式：' + (ZH[m[1]] || m[1]);
    m = source.match(/^Expression: (.+)$/);
    if (m) return '呈現方式：' + (ZH[m[1]] || m[1]);
    m = source.match(/^Thought for ([0-9.]+) seconds\. Show thinking steps$/);
    if (m) return '思考用時 ' + m[1] + ' 秒，查看思考步驟';
    m = source.match(/^([0-9]+) open · ([0-9]+) resolved$/);
    if (m) return m[1] + ' 則待處理 · ' + m[2] + ' 則已完成';
    m = source.match(/^([0-9]+) votes? · leading: (.+)$/);
    if (m) return m[1] + ' 票 · 目前領先：' + (ZH[m[2]] || m[2]);
    m = source.match(/^([0-9]+) vote[s]? · leading: (.+)$/);
    if (m) return m[1] + ' 票 · 目前領先：' + (ZH[m[2]] || m[2]);
    m = source.match(/^([0-9]+) vote[s]? · leading:$/);
    if (m) return m[1] + ' 票 · 目前領先：';
    m = source.match(/^CS\.0([1-4]) · (.+)$/);
    if (m) return '案例 CS.0' + m[1] + ' · ' + m[2];
    m = source.match(/^ease-out · default$/);
    if (m) return '減速 · 預設';
    m = source.match(/^(.+) · from Animate$/);
    if (m) return (ZH[m[1]] || m[1]) + ' · 由動畫工具設定';
    m = source.match(/^weight ([0-9]+) · tracking (-?[0-9.]+em) · ([0-9]+%)(( · caps)?( · outline)?)$/);
    if (m) return '字重 ' + m[1] + ' · 字距 ' + m[2] + ' · ' + m[3] + (m[4].indexOf('caps') > -1 ? ' · 大寫' : '') + (m[4].indexOf('outline') > -1 ? ' · 外框' : '');
    m = source.match(/^INSIGHT (0[1-6])$/);
    if (m) return '觀察 ' + m[1];
    m = source.match(/^([0-9]+) votes? · leading: (.+)$/);
    if (m) return m[1] + ' 票 · 目前領先：' + (ZH[m[2]] || m[2]);
    m = source.match(/^(Mon|Tue|Wed|Thu|Fri|Sat|Sun) ([0-9]{2}:[0-9]{2} Taipei)( · now .+)$/);
    if (m) return ZH[m[1]] + ' ' + m[2].replace(' Taipei', ' 台北') + ' · 現在 ' + m[3].replace(' · now ', '');
    m = source.match(/^(Mon|Tue|Wed|Thu|Fri|Sat|Sun) ([0-9]{2}:[0-9]{2} Taipei)$/);
    if (m) return ZH[m[1]] + ' ' + m[2].replace(' Taipei', ' 台北');
    m = source.match(/^Frame \/ Work \/ (.+)$/);
    if (m) return '畫面 / 作品 / ' + (ZH[m[1]] || m[1]);
    m = source.match(/^Component \/ (.+)$/);
    if (m) return '元件 / ' + m[1];
    m = source.match(/^([A-Z][A-Za-z0-9]+) case study$/);
    if (m) return m[1] + ' 專案案例';
    return source;
  }

  function localizeText(node) {
    var raw = node.nodeValue;
    if (!raw || !raw.trim()) return;
    var leading = (raw.match(/^\s*/) || [''])[0];
    var trailing = (raw.match(/\s*$/) || [''])[0];
    var core = raw.slice(leading.length, raw.length - trailing.length);
    if (!core) return;
    var memo = textMemory.get(node);
    var source = memo && core === memo.last ? memo.source : sourceOf(core);
    var next = translated(source, lang);
    textMemory.set(node, { source: source, last: next });
    if (next !== core) node.nodeValue = leading + next + trailing;
  }

  function localizeAttribute(el, name) {
    if (!el.hasAttribute(name)) return;
    var raw = el.getAttribute(name);
    if (!raw) return;
    var memo = attrMemory.get(el) || Object.create(null);
    var source = memo[name] && raw === memo[name].last ? memo[name].source : sourceOf(raw);
    var next = translated(source, lang);
    memo[name] = { source: source, last: next };
    attrMemory.set(el, memo);
    if (next !== raw) el.setAttribute(name, next);
  }

  function walk(node) {
    if (node.nodeType === 3) {
      var parent = node.parentElement;
      if (!parent || parent.closest('script, style, noscript, code, pre')) return;
      localizeText(node);
      return;
    }
    if (node.nodeType !== 1 && node.nodeType !== 9 && node.nodeType !== 11) return;
    if (node.nodeType === 1) ATTRS.forEach(function (name) { localizeAttribute(node, name); });
    var walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    var texts = [];
    while (walker.nextNode()) texts.push(walker.currentNode);
    texts.forEach(localizeText);
    if (node.querySelectorAll) {
      var all = node.querySelectorAll('*');
      for (var i = 0; i < all.length; i++) ATTRS.forEach(function (name) { localizeAttribute(all[i], name); });
    }
  }

  function apply(next) {
    lang = next === 'zh' ? 'zh' : 'en';
    if (document.body) walk(document.body);
    document.title = translated('Tom Lin — UI/UX Designer', lang);
  }

  window.V3I18n = {
    lang: function () { return lang; },
    t: function (value) { return translated(sourceOf(value), lang); },
    apply: apply
  };

  if (document.body) apply(lang);
  document.addEventListener('pfx-lang-change', function (e) {
    apply(e.detail && e.detail.lang ? e.detail.lang : (window.PfxI18n ? window.PfxI18n.getLang() : 'en'));
  });

  if (document.body && window.MutationObserver) {
    var observer = new MutationObserver(function (records) {
      records.forEach(function (record) {
        if (record.type === 'characterData') localizeText(record.target);
        else if (record.type === 'attributes') localizeAttribute(record.target, record.attributeName);
        else for (var i = 0; i < record.addedNodes.length; i++) walk(record.addedNodes[i]);
      });
    });
    observer.observe(document.body, {
      subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS
    });
  }
